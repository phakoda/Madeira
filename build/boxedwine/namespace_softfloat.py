#!/usr/bin/env python3
"""Keep BoxedWine's SoftFloat symbols separate from FEX's modified SoftFloat."""
import argparse
from pathlib import Path
import re


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    # These are the upstream library's public/helper symbol families. Types
    # float32_t/extFloat80_t retain their names and remain private to the engine.
    pattern = re.compile(r'\b(?:softfloat_|f(?:16|32|64|128)M?_|extF80M?_|(?:i|ui)(?:32|64)_to_)[A-Za-z0-9_]+\b')
    already_prefixed = re.compile(r'\bmadeira_bw_((?:softfloat_|f(?:16|32|64|128)M?_|extF80M?_|(?:i|ui)(?:32|64)_to_)[A-Za-z0-9_]+)\b')
    tokens = re.compile(r'"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|//[^\n]*|/\*[\s\S]*?\*/|(?P<name>\b[A-Za-z_][A-Za-z_0-9]*\b)')
    symbols = set()
    updates = {}
    for path in (args.source / 'lib/softfloat/source').rglob('*'):
        if path.suffix in ('.c', '.h'):
            text = path.read_text()
            def rename(match):
                name = match.group('name')
                if name and pattern.fullmatch(name):
                    symbols.add(name)
                    return 'madeira_bw_' + name
                if name and (previous := already_prefixed.fullmatch(name)):
                    symbols.add(previous.group(1))
                return match.group()
            updates[path] = tokens.sub(rename, text)
    if not {'softfloat_roundingMode', 'softfloat_raiseFlags', 'extF80_to_f64', 'f32_add'} <= symbols:
        raise RuntimeError('Unexpected SoftFloat source symbol families')
    args.output.parent.mkdir(parents=True, exist_ok=True)
    # Rename declarations, definitions, and #ifdef names together. Merely
    # force-defining aliases inside SoftFloat would change its #ifndef-based
    # choice of optimized primitives and omit required implementations.
    for path, text in updates.items():
        path.write_text(text)
    args.output.write_text('// Generated by namespace_softfloat.py; do not edit.\n#pragma once\n' +
        ''.join(f'#define {symbol} madeira_bw_{symbol}\n' for symbol in sorted(symbols)))
    print(f'Isolated {len(symbols)} BoxedWine SoftFloat names from FEX')


if __name__ == '__main__':
    main()
